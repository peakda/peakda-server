CREATE TABLE spot_record_photo_deletions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_key TEXT NOT NULL,
    owner_id BIGINT NOT NULL,
    evidence VARCHAR(64) NOT NULL,
    variant_names TEXT NOT NULL,
    completed_variants TEXT NOT NULL DEFAULT '',
    deletion_started BOOLEAN NOT NULL DEFAULT false,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    total_attempts INTEGER NOT NULL DEFAULT 0,
    reprocess_count INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL,
    lease_until TIMESTAMPTZ,
    claim_token UUID,
    last_error TEXT,
    finished_at TIMESTAMPTZ,
    outcome VARCHAR(64),
    CONSTRAINT ck_photo_deletion_status CHECK (status IN ('PENDING','PROCESSING','RETRYABLE','COMPLETED','FAILED')),
    CONSTRAINT ck_photo_deletion_attempts CHECK (attempts >= 0 AND total_attempts >= attempts AND reprocess_count >= 0),
    CONSTRAINT ck_photo_deletion_claim CHECK ((status = 'PROCESSING' AND lease_until IS NOT NULL AND claim_token IS NOT NULL) OR (status <> 'PROCESSING' AND lease_until IS NULL AND claim_token IS NULL))
);
-- FK를 두지 않는다. 탈퇴 후에도 소유 증거와 커밋된 정리 작업을 보존한다.
CREATE UNIQUE INDEX uq_photo_deletion_active ON spot_record_photo_deletions(object_key) WHERE status <> 'COMPLETED';
CREATE INDEX idx_photo_deletion_due ON spot_record_photo_deletions(next_attempt_at, id) WHERE status IN ('PENDING','RETRYABLE');
CREATE INDEX idx_photo_deletion_lease ON spot_record_photo_deletions(lease_until, id) WHERE status = 'PROCESSING';
COMMENT ON TABLE spot_record_photo_deletions IS '마지막 참조 해제와 함께 커밋하는 사진 전용 삭제 작업 및 variant별 재시도 증거';
