package com.peakda.server.domain.seasonal.entity

/**
 * 명소×카테고리의 개화/단풍 상태. 절정을 향해 가는 시간 순으로 선언한다.
 *
 * 지도 핀과 뱃지는 다섯 단계를 모두 노출한다. 예전에는 앞 3단계만 쓰고 [ENDED] 를 내부 전이
 * 상태로만 뒀는데, 그 탓에 절정이 반년 남은 명소와 코앞인 명소가 같은 뱃지를 달았다.
 */
enum class BloomStatus {
    /** 개화전 — 절정까지 아직 멀어 이번 시즌이라 부를 수 없는 구간. */
    BEFORE_SEASON,

    /** 이르다 — 절정이 1~2주 앞으로 다가와 미리 계획할 만한 구간. */
    PREPARING,

    /** 시작 — 피기 시작해 절정이 코앞인 구간. */
    STARTED,

    /** 절정 — 절정 구간. */
    PEAK,

    /** 늦었다 — 절정이 지난 구간. */
    ENDED,
}
